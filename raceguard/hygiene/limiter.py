"""Generating a rate limiter when the application has none.

If ``missing_rate_limit`` fires, ``raceguard fix --rule missing_rate_limit``
emits a working limiter rather than advice.

Token bucket, because token bucket is what most public APIs actually use:
normal traffic is bursty (batch jobs, app launches, retry storms), and a bucket
accumulates credit while idle and permits a burst up to capacity without
falsely limiting a well behaved client.

GCRA is the memory efficient alternative, storing a single theoretical arrival
time instead of a token count and needing no refill bookkeeping, but you cannot
ask it how many tokens remain, which makes it harder to debug. Token bucket
with explicit state is the better default for generated code a human will
maintain.

Both variants advertise quota in both spellings: the older
``RateLimit-Limit`` / ``-Remaining`` / ``-Reset`` triple that remains the de
facto deployed convention, and the newer combined ``RateLimit`` and
``RateLimit-Policy`` fields from the active IETF httpapi draft.
"""

from __future__ import annotations

from dataclasses import dataclass

IN_PROCESS = '''\
"""Token bucket rate limiter, generated by RaceGuard.

HONEST CAVEAT, and it is the first thing to read: this holds its state in
process memory. Running N workers therefore gives N times the configured
limit. This is a starting point that makes an unlimited endpoint limited, not
a distributed limiter. Move to the Redis variant the moment you run more than
one process.
"""

from __future__ import annotations

import time
from dataclasses import dataclass, field

from starlette.middleware.base import BaseHTTPMiddleware
from starlette.requests import Request
from starlette.responses import JSONResponse


@dataclass
class Bucket:
    tokens: float
    last: float


@dataclass
class TokenBucketLimiter:
    capacity: float            # burst size
    refill_per_second: float   # sustained rate
    _buckets: dict[str, Bucket] = field(default_factory=dict)

    def allow(self, key: str, cost: float = 1.0) -> tuple[bool, float, float]:
        """(allowed, seconds until allowed, tokens remaining)."""
        now = time.monotonic()
        bucket = self._buckets.get(key)
        if bucket is None:
            bucket = self._buckets[key] = Bucket(self.capacity, now)
        bucket.tokens = min(
            self.capacity, bucket.tokens + (now - bucket.last) * self.refill_per_second
        )
        bucket.last = now
        if bucket.tokens >= cost:
            bucket.tokens -= cost
            return True, 0.0, bucket.tokens
        deficit = cost - bucket.tokens
        return False, deficit / self.refill_per_second, bucket.tokens


class RateLimitMiddleware(BaseHTTPMiddleware):
    """Advertises quota in BOTH header spellings.

    The older RateLimit-Limit / -Remaining / -Reset triple is what is actually
    deployed and what most clients read. The combined RateLimit and
    RateLimit-Policy fields come from the active IETF httpapi draft. Emitting
    both costs nothing and means neither kind of client is left guessing.
    """

    def __init__(
        self,
        app,
        capacity: float = {capacity},
        refill_per_second: float = {refill},
        window_seconds: int = {window},
    ) -> None:
        super().__init__(app)
        self.limiter = TokenBucketLimiter(capacity, refill_per_second)
        self.capacity = capacity
        self.window_seconds = window_seconds

    def key_for(self, request: Request) -> str:
        # Prefer an authenticated identity over an IP address: behind a proxy
        # or CGNAT, limiting by IP punishes whole networks for one caller.
        user = request.headers.get("authorization")
        if user:
            return f"auth:{{hash(user)}}"
        client = request.client
        return f"ip:{{client.host if client else 'unknown'}}"

    async def dispatch(self, request: Request, call_next):
        # Cost weighting: a write costs more than a read, the way GitHub
        # charges roughly one point for a read and five for a write.
        cost = 5.0 if request.method in {{"POST", "PUT", "PATCH", "DELETE"}} else 1.0
        allowed, retry_after, remaining = self.limiter.allow(self.key_for(request), cost)

        if not allowed:
            headers = self._headers(remaining, retry_after)
            headers["Retry-After"] = str(max(1, int(retry_after + 0.999)))
            return JSONResponse(
                {{"detail": "rate limit exceeded"}}, status_code=429, headers=headers
            )

        response = await call_next(request)
        for name, value in self._headers(remaining, retry_after).items():
            response.headers[name] = value
        return response

    def _headers(self, remaining: float, reset_in: float) -> dict[str, str]:
        limit = str(int(self.capacity))
        remaining_str = str(max(0, int(remaining)))
        reset = str(max(0, int(reset_in + 0.999)))
        return {{
            # de facto deployed convention
            "RateLimit-Limit": limit,
            "RateLimit-Remaining": remaining_str,
            "RateLimit-Reset": reset,
            # IETF httpapi draft
            "RateLimit": f"limit={{limit}}, remaining={{remaining_str}}, reset={{reset}}",
            "RateLimit-Policy": f"{{limit}};w={{self.window_seconds}}",
        }}


# Wire it up:
#     from .rate_limit import RateLimitMiddleware
#     app.add_middleware(RateLimitMiddleware)
#
# Consider also, separately from this rate cap, a CONCURRENCY cap: GitHub caps
# concurrent requests independently of the hourly quota, because a burst of
# simultaneous requests is a different failure mode from a high sustained rate.
'''

REDIS = '''\
"""Distributed token bucket, generated by RaceGuard.

The refill-and-take must be ONE atomic operation or the limiter has the same
class of race this tool exists to find: two workers both read the token count,
both decide there is room, and both proceed. A Lua script runs atomically
inside Redis, which is what makes this correct across processes.
"""

from __future__ import annotations

import time

from redis.asyncio import Redis
from starlette.middleware.base import BaseHTTPMiddleware
from starlette.requests import Request
from starlette.responses import JSONResponse

# KEYS[1] bucket key. ARGV: capacity, refill_per_second, now, cost.
TOKEN_BUCKET_LUA = """
local state = redis.call('HMGET', KEYS[1], 'tokens', 'ts')
local capacity = tonumber(ARGV[1])
local refill = tonumber(ARGV[2])
local now = tonumber(ARGV[3])
local cost = tonumber(ARGV[4])

local tokens = tonumber(state[1])
local ts = tonumber(state[2])
if tokens == nil then
  tokens = capacity
  ts = now
end

tokens = math.min(capacity, tokens + (now - ts) * refill)
local allowed = 0
if tokens >= cost then
  tokens = tokens - cost
  allowed = 1
end

redis.call('HMSET', KEYS[1], 'tokens', tokens, 'ts', now)
redis.call('EXPIRE', KEYS[1], math.ceil(capacity / refill) + 1)
return {{allowed, tostring(tokens)}}
"""


class RedisTokenBucket:
    def __init__(self, redis: Redis, capacity: float, refill_per_second: float) -> None:
        self.redis = redis
        self.capacity = capacity
        self.refill_per_second = refill_per_second
        self._script = redis.register_script(TOKEN_BUCKET_LUA)

    async def allow(self, key: str, cost: float = 1.0) -> tuple[bool, float]:
        allowed, tokens = await self._script(
            keys=[f"rl:{{key}}"],
            args=[self.capacity, self.refill_per_second, time.time(), cost],
        )
        return bool(int(allowed)), float(tokens)


class RedisRateLimitMiddleware(BaseHTTPMiddleware):
    def __init__(
        self,
        app,
        redis: Redis,
        capacity: float = {capacity},
        refill_per_second: float = {refill},
        window_seconds: int = {window},
    ) -> None:
        super().__init__(app)
        self.bucket = RedisTokenBucket(redis, capacity, refill_per_second)
        self.capacity = capacity
        self.window_seconds = window_seconds

    async def dispatch(self, request: Request, call_next):
        cost = 5.0 if request.method in {{"POST", "PUT", "PATCH", "DELETE"}} else 1.0
        client = request.client
        key = request.headers.get("authorization") or (client.host if client else "unknown")
        allowed, remaining = await self.bucket.allow(key, cost)

        limit = str(int(self.capacity))
        remaining_str = str(max(0, int(remaining)))
        headers = {{
            "RateLimit-Limit": limit,
            "RateLimit-Remaining": remaining_str,
            "RateLimit-Reset": str(self.window_seconds),
            "RateLimit": f"limit={{limit}}, remaining={{remaining_str}}, reset={{self.window_seconds}}",
            "RateLimit-Policy": f"{{limit}};w={{self.window_seconds}}",
        }}
        if not allowed:
            headers["Retry-After"] = str(self.window_seconds)
            return JSONResponse(
                {{"detail": "rate limit exceeded"}}, status_code=429, headers=headers
            )
        response = await call_next(request)
        for name, value in headers.items():
            response.headers[name] = value
        return response
'''


@dataclass
class LimiterSpec:
    capacity: float = 60.0
    refill_per_second: float = 1.0
    window_seconds: int = 60
    distributed: bool = False

    def render(self) -> str:
        template = REDIS if self.distributed else IN_PROCESS
        return template.format(
            capacity=self.capacity,
            refill=self.refill_per_second,
            window=self.window_seconds,
        )

    @property
    def filename(self) -> str:
        return "rate_limit_redis.py" if self.distributed else "rate_limit.py"


def generate(spec: LimiterSpec | None = None) -> tuple[str, str]:
    spec = spec or LimiterSpec()
    return spec.filename, spec.render()
