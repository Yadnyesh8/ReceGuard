def _collect_models(files: list[Path]) -> dict[str, ModelInfo]:
    models: dict[str, ModelInfo] = {}
    for path in files:
        try:
            source = path.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError):
            continue
        if "__tablename__" not in source:
            continue
        try:
            module = cst.parse_module(source)
        except cst.ParserSyntaxError:
            continue
        for statement in module.body:
            if not isinstance(statement, cst.ClassDef):
                continue
            rendered = cst.Module(body=[statement]).code
            match = re.search(r"__tablename__\s*=\s*[\"']([^\"']+)[\"']", rendered)
            if not match:
                continue
            info = ModelInfo(name=statement.name.value, table=match.group(1))
            for line in statement.body.body:
                if not isinstance(line, cst.SimpleStatementLine):
                    continue
                for small in line.body:
                    if isinstance(small, cst.AnnAssign) and isinstance(small.target, cst.Name):
                        name = small.target.value
                        if name.startswith("__"):
                            continue
                        annotation = cst.Module(body=[]).code_for_node(small.annotation.annotation)
                        info.columns[name] = _inner_type(annotation)
                        rendered_value = (
                            cst.Module(body=[]).code_for_node(small.value) if small.value else ""
                        )
                        if (
                            "nullable=False" in rendered_value
                            or "primary_key=True" in rendered_value
                        ):
                            info.non_null.add(name)
            models[info.name] = info
    return models


def _inner_type(annotation: str) -> str:
    match = re.search(r"\[([^\]]+)\]", annotation)
    return (match.group(1) if match else annotation).strip().lower()


def _collect_schemas(files: list[Path]) -> dict[str, SchemaInfo]:
    """Pydantic request models, so payloads are generated rather than guessed."""
    schemas: dict[str, SchemaInfo] = {}
    for path in files:
        try:
            source = path.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError):
            continue
        if "BaseModel" not in source:
            continue
        try:
            module = cst.parse_module(source)
        except cst.ParserSyntaxError:
            continue
        for statement in module.body:
            if not isinstance(statement, cst.ClassDef):
                continue
            bases = " ".join(cst.Module(body=[]).code_for_node(b.value) for b in statement.bases)
            if "BaseModel" not in bases:
                continue
            info = SchemaInfo(name=statement.name.value)
            for line in statement.body.body:
                if not isinstance(line, cst.SimpleStatementLine):
                    continue
                for small in line.body:
                    if isinstance(small, cst.AnnAssign) and isinstance(small.target, cst.Name):
                        annotation = cst.Module(body=[]).code_for_node(small.annotation.annotation)
                        info.fields[small.target.value] = annotation.strip().lower()
            if info.fields:
                schemas[info.name] = info
    return schemas


def _guess_app_module(files: list[Path], root: Path) -> str | None:
    for path in files:
        try:
            source = path.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError):
            continue
        if "FastAPI" not in source:
            continue
        # Either `app = FastAPI(...)` directly, or the very common factory
        # form `app = create_app()` in a module that imports FastAPI.
        match = re.search(r"^(\w+)\s*=\s*FastAPI\(", source, re.MULTILINE)
        if match is None:
            match = re.search(r"^(app|application)\s*=\s*\w+\(\s*\)", source, re.MULTILINE)
        if not match:
            continue
        try:
            relative = path.resolve().relative_to(root.resolve())
        except ValueError:
            continue
        module = str(relative.with_suffix("")).replace("/", ".").removesuffix(".__init__")
        return f"{module}:{match.group(1)}"
    return None


def _inline(value: Any) -> str:
    """Flow-style YAML, so a generated seed row stays one readable line."""
    import yaml

    return yaml.safe_dump(value, default_flow_style=True, width=200).strip()
