"""`raceguard init`: generate raceguard.yaml from a scan.

Nobody hand writes that file, and a tool that requires them to will be tried
once. This generator reads routes from the decorators, payloads from the
endpoint's Pydantic request model, seed rows from the SQLAlchemy model with
boundary values filled in, and invariants from schema constraints.

Two rules it holds to:

* Never invent an invariant silently. Anything inferred rather than read from a
  constraint is written as a COMMENTED suggestion the user has to confirm.
* Seed tight. `stock = 1` with concurrency 2 is a far better signal than
  `stock = 100` with concurrency 50, because the final state distinguishes a
  violation cleanly rather than burying it in noise.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import libcst as cst

from .contracts import Confidence, Finding
from .scanner import ScanOptions, iter_python_files
from .scanner import scan as run_scan

HEADER = """\
# Generated by `raceguard init`. Review before running anything.
#
# Three things need a human decision and are marked inline:
#   1. auth headers      - RaceGuard cannot know how your app authenticates.
#   2. payload values    - guessed from the request model's field types.
#   3. any invariant marked SUGGESTION - inferred, not read from a constraint.
#
# Seeds are deliberately tight. stock = 1 with concurrency 2 exposes an
# oversell far more clearly than stock = 100 with concurrency 50, because the
# final state distinguishes a violation instead of burying it in noise.
"""

# Boundary values by field type. The point is the tightest state that can
# expose the invariant, not a realistic one.
_BOUNDARY = {
    "int": 1,
    "integer": 1,
    "float": 1.0,
    "decimal": 1.0,
    "str": "rg-1",
    "string": "rg-1",
    "bool": True,
    "uuid": "00000000-0000-0000-0000-000000000001",
    "datetime": "2024-01-01T00:00:00Z",
}

_SEED_COLUMN_HINTS = ("stock", "balance", "quantity", "qty", "count", "remaining", "credits")


@dataclass
class ModelInfo:
    name: str
    table: str
    columns: dict[str, str] = field(default_factory=dict)
    non_null: set[str] = field(default_factory=set)


@dataclass
class SchemaInfo:
    name: str
    fields: dict[str, str] = field(default_factory=dict)


def generate_config(root: Path) -> str:
    result = run_scan([str(root)], ScanOptions(min_confidence=Confidence.low, root=root))
    files = iter_python_files([str(root)], ScanOptions().excludes)
    models = _collect_models(files)
    schemas = _collect_schemas(files)
    app_module = _guess_app_module(files, root)

    lines: list[str] = [HEADER, "version: 1", "", "app:"]
    lines.append(
        f'  module: "{app_module or "yourapp.main:app"}"'
        + ("" if app_module else "   # TODO: could not resolve this statically")
    )
    lines.append(
        '  start: "uvicorn %s --host 0.0.0.0 --port 8000"' % (app_module or "yourapp.main:app")
    )
    lines.append('  health_path: "/health"           # TODO: confirm this endpoint exists')
    lines.append('  base_url: "http://localhost:8000"')
    lines.append('  database_url_env: "DATABASE_URL"')
    lines.append("  # The driver your app expects in its URL. RaceGuard does not guess:")
    lines.append("  # an async app handed a sync URL fails at import with a useless error.")
    lines.append('  database_url_driver: "asyncpg"   # or "psycopg", or remove for sync')
    lines.append('  migrate: "alembic upgrade head"  # TODO: confirm your migration command')
    lines.append('  test_command: "pytest -q"')
    lines.append("")
    lines.append("database:")
    lines.append("  # Pin by digest before you rely on these numbers. A moved tag can")
    lines.append("  # silently change verification results.")
    lines.append('  image: "postgres:17-alpine"')
    lines.append("")
    lines.append("defaults:")
    lines.append("  mode: container")
    lines.append("  trials: 20")
    lines.append("  concurrency: 8")
    lines.append("  sync: barrier")
    lines.append("  amplify: true")
    lines.append("  amplify_ms: 25")
    lines.append("")
    lines.append("governor:")
    lines.append("  # RaceGuard is a load generator by construction. These caps are what")
    lines.append("  # keep it from being indistinguishable from an attack.")
    lines.append("  max_global_concurrency: 16")
    lines.append("  min_trial_spacing_ms: 250")
    lines.append("  max_requests_per_run: 5000")
    lines.append("")

    targets = [f for f in result.findings if f.confidence.rank() >= Confidence.medium.rank()]
    lines.append("targets:")
    if not targets:
        lines.append("  # No read-modify-write windows found above low confidence.")
        lines.append("  # Add targets by hand, or re-scan with --min-confidence low.")
    used_ids: set[str] = set()
    for finding in targets:
        lines.extend(_target_block(finding, models, schemas, used_ids, root))

    lines.append("")
    lines.append("hygiene:")
    lines.append("  enabled: true")
    lines.append("")
    lines.append("suppress: []")
    lines.append('  # - handler: "app/routes/admin.py::bulk_import"')
    lines.append("  #   rule: oversell")
    lines.append('  #   reason: "single admin caller, serialised upstream by the import queue"')
    lines.append("")
    return "\n".join(lines)


def _target_block(
    finding: Finding,
    models: dict[str, ModelInfo],
    schemas: dict[str, SchemaInfo],
    used_ids: set[str],
    root: Path,
) -> list[str]:
    # Two findings can share a handler (a transfer is an oversell on the debit
    # and a lost update on the credit), and two targets with the same id make
    # the file invalid rather than merely confusing.
    target_id = _unique(_target_id(finding), finding, used_ids)
    table = finding.tables[0] if finding.tables else None
    model = next((m for m in models.values() if m.table == table), None)
    column = finding.columns[0] if finding.columns else None

    lines = [
        "",
        f"  # {finding.pattern} at {finding.read_site.file}:{finding.read_site.start_line} "
        f"({finding.confidence.value} confidence)",
        f"  - id: {target_id}",
    ]
    if finding.route:
        lines.append(f'    route: "{finding.route}"')
    else:
        lines.append('    route: "POST /TODO"   # the route could not be resolved statically')
    lines.append(f'    handler: "{finding.read_site.file}::{finding.handler.rsplit(":", 1)[-1]}"')
    lines.append('    spec: "TODO: state the rule this endpoint must never break, in one sentence"')

    payload = _payload_for(finding, schemas, root)
    lines.append(f"    payload: {_inline(payload)}   # TODO: confirm these values")
    lines.append(
        '    # headers: { Authorization: "Bearer ${RG_TEST_TOKEN}" }   # TODO if authenticated'
    )

    if model is not None:
        lines.append("    seed:")
        lines.append(f"      {model.table}:")
        lines.append(f"        - {_inline(_seed_row(model, column))}")
    elif table:
        lines.append("    seed:")
        lines.append(f"      {table}:")
        lines.append("        - { id: 1 }   # TODO: fill in the columns this handler reads")

    lines.extend(_invariant_block(finding, table, column))
    lines.append("    concurrency: 2")
    lines.append("    trials: 20")
    return lines


def _invariant_block(finding: Finding, table: str | None, column: str | None) -> list[str]:
    if table is None:
        return [
            "    # invariant: could not infer one. State it here or give a spec sentence",
            "    #   and let the synthesizer derive it against the live schema.",
        ]
    kind = {
        "oversell": "non_negative",
        "lost_update": "conservation",
        "single_use": "single_use",
        "duplicate_insert": "duplicate_insert",
        "aggregate_limit": "aggregate_limit",
    }[finding.pattern]

    lines = [
        "    # SUGGESTION, inferred from the pattern rather than read from a",
        "    # constraint. Confirm it, then delete this comment. If the handler",
        "    # decrements through an ORM attribute rather than in SQL, a",
        "    # non_negative check will NOT catch the oversell: both requests",
        "    # write the same value. Use a conservation check in that case.",
        "    invariant:",
        f"      kind: {kind}",
        f"      table: {table}",
    ]
    if column:
        lines.append(f"      column: {column}")
    if kind == "aggregate_limit":
        lines.append("      limit: 1   # TODO: the real cap")
    return lines


def _target_id(finding: Finding) -> str:
    name = finding.handler.rsplit(":", 1)[-1].rsplit(".", 1)[-1]
    return re.sub(r"[^a-z0-9_]", "_", name.lower()) or "target"


def _unique(base: str, finding: Finding, used: set[str]) -> str:
    candidate = base
    if candidate in used:
        candidate = f"{base}_{finding.pattern}"
    suffix = 2
    while candidate in used:
        candidate = f"{base}_{suffix}"
        suffix += 1
    used.add(candidate)
    return candidate


def _payload_for(finding: Finding, schemas: dict[str, SchemaInfo], root: Path) -> dict[str, Any]:
    """Read the endpoint's request model from the handler's own signature.

    Matching on the code snippet was too loose; the annotation on the handler
    parameter is where the answer actually is.
    """
    handler_name = finding.handler.rsplit(":", 1)[-1].rsplit(".", 1)[-1]
    for annotation in _handler_annotations(root / finding.read_site.file, handler_name):
        schema = schemas.get(annotation)
        if schema is not None:
            return {field: _boundary(kind) for field, kind in schema.fields.items()}

    snippet = finding.read_site.snippet + (
        finding.decision_site.snippet if finding.decision_site else ""
    )
    guessed: dict[str, Any] = {}
    for match in re.finditer(r"payload\.(\w+)", snippet):
        guessed[match.group(1)] = 1
    return guessed or {"TODO": "the request body this endpoint expects"}


def _handler_annotations(path: Path, handler: str) -> list[str]:
    try:
        module = cst.parse_module(path.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, cst.ParserSyntaxError):
        return []
    found: list[str] = []

    class _V(cst.CSTVisitor):
        def visit_FunctionDef(self, node: cst.FunctionDef) -> None:
            if node.name.value != handler:
                return
            for param in node.params.params:
                if param.annotation is None:
                    continue
                rendered = cst.Module(body=[]).code_for_node(param.annotation.annotation)
                found.append(rendered.strip())

    module.visit(_V())
    return found


def _boundary(kind: str) -> Any:
    return _BOUNDARY.get(kind.lower(), "rg-1")


def _seed_row(model: ModelInfo, column: str | None) -> dict[str, Any]:
    row: dict[str, Any] = {"id": 1}
    for name, kind in model.columns.items():
        if name in {"id", "created_at", "updated_at"}:
            continue
        if name == column or any(hint in name.lower() for hint in _SEED_COLUMN_HINTS):
            row[name] = 1  # the boundary: one unit, so two requests contend
        elif name in model.non_null:
            row[name] = _boundary(kind)
    return row


