"""Emitted schema changes, in raw SQL and as the equivalent Alembic op.

When a strategy needs a schema change, the ``Migration`` travels with the patch
and the report states plainly that the code change alone is insufficient. A
patch that adds ``ON CONFLICT DO NOTHING`` to a table with no unique index is
not a fix; it is a no-op wearing the costume of one.
"""

from __future__ import annotations

from ..contracts import Migration


def unique_index(table: str, columns: list[str], *, name: str | None = None) -> Migration:
    index_name = name or f"uq_{table}_{'_'.join(columns)}"
    column_sql = ", ".join(f'"{c}"' for c in columns)
    return Migration(
        kind="unique_index",
        statement=(
            f"-- Required for ON CONFLICT to have anything to conflict against.\n"
            f"-- CONCURRENTLY avoids taking an exclusive lock on a live table, but it\n"
            f"-- cannot run inside a transaction; Alembic users need "
            f"autocommit_block().\n"
            f'CREATE UNIQUE INDEX CONCURRENTLY IF NOT EXISTS "{index_name}"\n'
            f'    ON "{table}" ({column_sql});'
        ),
        alembic=(
            f"with op.get_context().autocommit_block():\n"
            f"    op.create_index(\n"
            f"        {index_name!r},\n"
            f"        {table!r},\n"
            f"        {columns!r},\n"
            f"        unique=True,\n"
            f"        postgresql_concurrently=True,\n"
            f"        if_not_exists=True,\n"
            f"    )"
        ),
    )


def check_constraint(table: str, column: str, *, minimum: int = 0) -> Migration:
    name = f"ck_{table}_{column}_non_negative"
    return Migration(
        kind="check_constraint",
        statement=(
            f"-- NOT VALID skips the scan of existing rows, so this takes a brief\n"
            f"-- lock instead of a long one. VALIDATE afterwards, separately.\n"
            f'ALTER TABLE "{table}"\n'
            f'    ADD CONSTRAINT "{name}" CHECK ("{column}" >= {minimum}) NOT VALID;\n'
            f'ALTER TABLE "{table}" VALIDATE CONSTRAINT "{name}";'
        ),
        alembic=(
            f"op.create_check_constraint(\n"
            f"    {name!r}, {table!r}, {f'{column} >= {minimum}'!r}\n"
            f")"
        ),
    )


def version_column(table: str, *, column: str = "version") -> Migration:
    return Migration(
        kind="version_column",
        statement=(
            f"-- Added with a default so existing rows get a starting value, then\n"
            f"-- made NOT NULL. On a large table, backfill in batches first.\n"
            f'ALTER TABLE "{table}" ADD COLUMN IF NOT EXISTS "{column}" integer NOT NULL DEFAULT 1;'
        ),
        alembic=(
            f"op.add_column(\n"
            f"    {table!r},\n"
            f"    sa.Column({column!r}, sa.Integer(), nullable=False, server_default='1'),\n"
            f")"
        ),
    )


ALEMBIC_TEMPLATE = '''\
"""raceguard: {summary}

Generated by RaceGuard. Review before applying: this migration is part of a fix
for a concurrency defect, and the code change that accompanies it is not
sufficient on its own.

Revision ID: {revision}
Revises: {down_revision}
"""

from alembic import op
import sqlalchemy as sa

revision = {revision!r}
down_revision = {down_revision!r}
branch_labels = None
depends_on = None


def upgrade() -> None:
{upgrade}


def downgrade() -> None:
{downgrade}
'''


def render_alembic(
    migration: Migration, *, revision: str, down_revision: str | None, summary: str
) -> str:
    upgrade = "\n".join(f"    {line}" for line in migration.alembic.splitlines())
    downgrade = "    pass  # review: dropping this re-opens the defect"
    return ALEMBIC_TEMPLATE.format(
        summary=summary,
        revision=revision,
        down_revision=down_revision,
        upgrade=upgrade,
        downgrade=downgrade,
    )
